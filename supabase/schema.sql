-- =============================================================================
-- EmptyTrip Shillong - Supabase schema (CP1)
--
-- Run this FIRST in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Then run supabase/seed.sql.
--
-- Safe to re-run: tables use "if not exists" and policies are dropped/recreated.
-- NOTE: re-running does NOT alter an existing table. If you change a column here
-- after the tables exist, alter the table manually or drop and recreate it.
--
-- Field names mirror the existing frontend (src/data/trips.js, ListTrip.jsx,
-- FindRide.jsx) except:
--   * "from"/"to" are SQL reserved words -> columns are from_location / to_location.
--     The API layer (CP2, src/lib/api.js) will map them back to trip.from / trip.to.
--   * fromCoords / toCoords are NOT stored. The frontend derives them from
--     locationCoords in src/data/trips.js (they match the seed coordinates exactly).
--
-- SECURITY (demo-grade): there is no login. Row Level Security is enabled but the
-- policies are permissive for the public "anon" key: anyone holding the anon key
-- can read and insert trips and ride requests. There are NO delete policies, and no update
-- policy on trips. The ONLY update allowed is ride_requests.status pending -> accepted or
-- declined (CP5-E, see the section near the end of this file for its limits).
-- Do not store data you would not want to be public.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- trips
-- -----------------------------------------------------------------------------
create table if not exists public.trips (
  -- "by default" (not "always") so seed.sql can insert the original ids 1-10.
  id             bigint generated by default as identity primary key,

  driver         text        not null,
  phone          text        not null,
  from_location  text        not null,   -- frontend: trip.from
  to_location    text        not null,   -- frontend: trip.to

  -- ListTrip.jsx collects a date; seed trips have none, so nullable.
  date           date,

  -- Kept as text: seed trips use "4:30 PM", ListTrip's <input type="time"> yields "16:30".
  departure      text        not null,

  seats          integer     not null check (seats > 0),
  vehicle        text        not null,
  fare           integer     not null check (fare >= 0),   -- rupees per person

  notes          text,                                     -- listed trips only
  rating         numeric(2,1) check (rating between 0 and 5),  -- seed trips only
  pickup         text,                                     -- seed trips only

  -- NEW (not in current frontend): random per-browser id so a driver can find their own
  -- trips later. Null for seed trips. Not a secret; not authentication.
  driver_key     text,

  created_at     timestamptz not null default now()        -- NEW
);

create index if not exists trips_route_idx      on public.trips (from_location, to_location);
create index if not exists trips_driver_key_idx on public.trips (driver_key);


-- -----------------------------------------------------------------------------
-- ride_requests   (entirely new: today a "request" is only a trip id in localStorage)
-- -----------------------------------------------------------------------------
create table if not exists public.ride_requests (
  id               bigint generated by default as identity primary key,

  trip_id          bigint      not null references public.trips (id) on delete cascade,

  passenger_name   text        not null,
  passenger_phone  text        not null,

  -- Today's UI implies exactly one seat per request.
  seats_requested  integer     not null default 1 check (seats_requested >= 1),

  -- 'accepted' / 'declined' are set by the driver inbox (CP5-E); see the UPDATE section below.
  status           text        not null default 'pending'
                   check (status in ('pending', 'accepted', 'declined')),

  -- Random per-browser id so Home can list "Your Requests". Not a secret.
  passenger_key    text        not null,

  created_at       timestamptz not null default now()
);

create index if not exists ride_requests_trip_idx      on public.ride_requests (trip_id);
create index if not exists ride_requests_passenger_idx on public.ride_requests (passenger_key);


-- -----------------------------------------------------------------------------
-- Privileges (explicit, so behaviour does not depend on project default privileges)
-- -----------------------------------------------------------------------------
grant usage on schema public to anon, authenticated;

grant select, insert on public.trips         to anon, authenticated;
grant select, insert on public.ride_requests to anon, authenticated;


-- -----------------------------------------------------------------------------
-- Row Level Security (demo-grade, permissive read + insert; see SECURITY note above)
-- -----------------------------------------------------------------------------
alter table public.trips         enable row level security;
alter table public.ride_requests enable row level security;

drop policy if exists "trips_select_all" on public.trips;
create policy "trips_select_all"
  on public.trips for select
  to anon, authenticated
  using (true);

drop policy if exists "trips_insert_all" on public.trips;
create policy "trips_insert_all"
  on public.trips for insert
  to anon, authenticated
  with check (true);

drop policy if exists "ride_requests_select_all" on public.ride_requests;
create policy "ride_requests_select_all"
  on public.ride_requests for select
  to anon, authenticated
  using (true);

drop policy if exists "ride_requests_insert_all" on public.ride_requests;
create policy "ride_requests_insert_all"
  on public.ride_requests for insert
  to anon, authenticated
  with check (true);

-- -----------------------------------------------------------------------------
-- CP5-E: driver accepts / declines a request  (UPDATE on ride_requests.status ONLY)
--
-- Needed by updateRequestStatus() in src/lib/api.js. Safe to re-run.
--
-- What it allows (anon and authenticated):
--   * UPDATE of the "status" column ONLY (column-level grant; every other column is read-only).
--   * Only on rows whose CURRENT status is 'pending'        (policy USING).
--   * Only to a NEW status of 'accepted' or 'declined'      (policy WITH CHECK).
-- What it does NOT allow:
--   * Any other status value, or setting a request back to 'pending'.
--   * Changing an accepted/declined request again (it is final).
--   * Editing passenger name/phone, seats, trip_id, passenger_key or created_at.
--   * Any DELETE, and any UPDATE on trips.
--
-- SECURITY LIMITATION (read this): the app has NO login. "driver_key" is a random value
-- generated by each browser and is NOT a trusted identity, so the database cannot prove
-- that the caller owns the trip. The driver_key filter in updateRequestStatus() is
-- application-side filtering only, NOT a security boundary. Anyone holding the public anon
-- key who knows (or enumerates; SELECT is open) a pending request id can accept or decline
-- it, on any trip. The database also does not check trip capacity when accepting.
-- This is accepted for the demo/classroom prototype. A real system needs Supabase Auth (or
-- another trusted identity) plus a policy tied to the authenticated user.
-- -----------------------------------------------------------------------------

-- Revoke first so the result does not depend on project default privileges (Supabase may
-- grant full table privileges by default); then grant back the single column.
revoke update on public.ride_requests from anon, authenticated;
grant update (status) on public.ride_requests to anon, authenticated;

drop policy if exists "ride_requests_update_status" on public.ride_requests;
create policy "ride_requests_update_status"
  on public.ride_requests for update
  to anon, authenticated
  using (status = 'pending')
  with check (status in ('accepted', 'declined'));

-- Intentionally NOT created:
--   * Any DELETE policy, on either table.
--   * Any UPDATE grant or policy on trips.
